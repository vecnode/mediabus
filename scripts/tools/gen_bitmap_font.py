def pack(rows):
    """7 rows x 5 cols -> 5 bytes, one per column, bit y = row y."""
    cols = []
    for x in range(5):
        byte = 0
        for y in range(7):
            if rows[y][x] == "#":
                byte |= 1 << y
        cols.append(byte)
    return cols


def main():
    print("// GENERATED by scripts/tools/gen_bitmap_font.py - do not edit by hand.")
    print("// 5x7 atlas: 5 bytes per glyph, one per column, bit y = row y (LSB = top).")
    print("// Span covers ASCII 32 (' ') through 95 ('_'); input is folded to uppercase.")
    print()
    print("// clang-format off")
    first = 32
    chars = [chr(c) for c in range(first, 96)]
    missing = [c for c in chars if c not in ART]
    if missing:
        raise SystemExit("missing glyph art for: %r" % missing)

    print("const std::uint8_t kGlyphs[][5] = {")
    for ch in chars:
        rows = ART[ch]
        assert len(rows) == 7, ch
        assert all(len(r) == 5 for r in rows), ch
        cols = pack(rows)
        label = ch if ch not in ('"', "\\") else ("\\\"" if ch == '"' else "\\\\")
        # emit the art as a comment so the table stays readable
        art = " | ".join(rows)
        print("    {%s},  // '%s'  %s" % (
            ", ".join("0x%02X" % c for c in cols), label, art))
    print("};")
    print("// clang-format on")


if __name__ == "__main__":
    main()
